# frozen_string_literal: true

require 'fileutils'

module CorpusCli
  class DiagramGenerator
    SAFETY_COLOURS = {
      'read_only' => 'green',
      'mutating' => 'yellow',
      'destructive' => 'red'
    }.freeze

    STATUS_MARKERS = {
      completed: '[x]',
      in_progress: '[>]',
      failed: '[!]',
      pending: '[ ]'
    }.freeze

    def initialize(state_tracker: nil)
      @state_tracker = state_tracker
    end

    def ascii(workflow, completed_ids = nil)
      completed_ids ||= completed_from_tracker(workflow)
      lines = []

      lines << box_line(workflow.display_name)
      lines << "  #{workflow.description}" if workflow.description
      lines << ""

      pipeline = workflow.pipeline_order
      pipeline.each_with_index do |step, idx|
        status = step_status(step, completed_ids)
        marker = STATUS_MARKERS[status]
        safety = step.safety_label

        line = "  #{marker} #{step.display_name} #{safety}"
        line += "  [~#{step.estimated_duration}]" if step.estimated_duration
        lines << line

        if idx < pipeline.size - 1
          lines << "    |"
          lines << "    v"
        end
      end

      if workflow.auxiliary_steps.any?
        lines << ""
        lines << "  --- Auxiliary (run independently) ---"
        workflow.auxiliary_steps.each do |step|
          status = step_status(step, completed_ids)
          marker = STATUS_MARKERS[status]
          lines << "  #{marker} #{step.display_name} #{step.safety_label}"
        end
      end

      lines << ""
      lines << legend
      lines.join("\n")
    end

    def mermaid(workflow)
      lines = []
      lines << "```mermaid"
      lines << "flowchart TD"

      pipeline = workflow.pipeline_order
      pipeline.each do |step|
        node_id = step.id
        label = step.display_name
        safety_class = step.safety

        lines << "    #{node_id}[\"#{label}\"]"
        lines << "    class #{node_id} #{safety_class}"
      end

      workflow.auxiliary_steps.each do |step|
        lines << "    #{step.id}[\"#{step.display_name}\"]"
        lines << "    class #{step.id} #{step.safety}"
      end

      lines << ""

      pipeline.each do |step|
        step.prerequisites.each do |pre_id|
          lines << "    #{pre_id} --> #{step.id}"
        end
      end

      lines << ""
      lines << "    classDef read_only fill:#d4edda,stroke:#28a745"
      lines << "    classDef mutating fill:#fff3cd,stroke:#ffc107"
      lines << "    classDef destructive fill:#f8d7da,stroke:#dc3545"
      lines << "```"

      lines.join("\n")
    end

    def mermaid_doc(workflow)
      lines = []
      lines << "# #{workflow.display_name}"
      lines << ""
      lines << workflow.description if workflow.description
      lines << ""
      lines << "## Pipeline Diagram"
      lines << ""
      lines << mermaid(workflow)
      lines << ""
      lines << "## Steps"
      lines << ""

      (workflow.steps + workflow.auxiliary_steps).each do |step|
        lines << "### #{step.display_name}"
        lines << ""
        lines << "- **Task:** `#{step.task}`"
        lines << "- **Type:** #{step.type}"
        lines << "- **Safety:** #{step.safety} #{step.safety_label}"
        lines << "- **Duration:** #{step.estimated_duration}" if step.estimated_duration
        lines << "- **Prerequisites:** #{step.prerequisites.join(', ')}" if step.prerequisites.any?

        if step.params.any?
          lines << "- **Parameters:**"
          step.params.each do |p|
            lines << "  - `#{p.name}` (#{p.type}, default: #{p.default.inspect})"
          end
        end

        lines << "- **Description:** #{step.description}" if step.description
        lines << ""
      end

      lines << "---"
      lines << "*Generated by `bin/corpus diagram mermaid`*"
      lines.join("\n")
    end

    def generate_all_docs(registry, output_dir = nil)
      output_dir ||= File.expand_path('../../docs/workflows', __dir__)
      FileUtils.mkdir_p(output_dir)

      registry.workflows.each_value do |workflow|
        path = File.join(output_dir, "#{workflow.name}.md")
        File.write(path, mermaid_doc(workflow))
      end
    end

    private

    def completed_from_tracker(workflow)
      return Set.new unless @state_tracker
      @state_tracker.completed_steps(workflow.name)
    end

    def step_status(step, completed_ids)
      if completed_ids.include?(step.id)
        :completed
      elsif step.prerequisites.all? { |pre| completed_ids.include?(pre) }
        :pending
      else
        :pending
      end
    end

    def box_line(text)
      width = text.length + 4
      top = "+" + "-" * width + "+"
      mid = "|  #{text}  |"
      bot = "+" + "-" * width + "+"
      "#{top}\n#{mid}\n#{bot}"
    end

    def legend
      "Legend: [x]=done [ ]=pending [!]=failed [>]=running  (R)=read-only (M)=mutating (D)=destructive"
    end
  end
end
